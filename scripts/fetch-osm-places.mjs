// fetch-osm-places.mjs — snapshot of Los Angeles County food places from OpenStreetMap (M9; refreshed in M13).
//
//   node scripts/fetch-osm-places.mjs > refresh.sql                  asks Overpass (tries three servers)
//   node scripts/fetch-osm-places.mjs saved.json > refresh.sql       reuses a saved Overpass response
//   node scripts/fetch-osm-places.mjs --save raw.json > refresh.sql  asks Overpass and keeps its response
//
// Prints a migration that replaces every `resources` row (the table's shape is M9's: 20261002174017_m9_real_map.sql);
// counts go to stderr. Review the SQL, then apply it as a new migration (never edit an applied one). "as of" is the OSM
// data's own timestamp, not today's date: public Overpass mirrors can lag the live map by months.
// Specs: docs/superpowers/specs/2026-10-02-m9-real-map-design.md §3; M13 adds amenity=food_sharing (community fridges)
// as free food and leaves out students-only pantries (docs/superpowers/specs/2026-10-07-m13-map-near-me-design.md §3.4).

import { readFileSync, writeFileSync } from "node:fs";
import { toPlace, studentsOnly } from "../src/lib/osmPlaces.ts";

const QUERY = `[out:json][timeout:180];area["wikidata"="Q104994"]->.la;(
nwr["amenity"="food_bank"](area.la);nwr["social_facility"="food_bank"](area.la);nwr["amenity"="food_sharing"](area.la);
nwr["amenity"="marketplace"](area.la);nwr["leisure"="garden"]["garden:type"="community"](area.la););out tags center;`;
const SERVERS = ["https://overpass-api.de/api/interpreter", "https://overpass.private.coffee/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter"];

async function fetchOverpass() {
  for (const url of SERVERS) {
    try {
      const res = await fetch(url, { method: "POST", body: new URLSearchParams({ data: QUERY }),
        headers: { "User-Agent": "EcoGo/0.1 (personal project)" }, signal: AbortSignal.timeout(200_000) });
      const text = await res.text();
      if (res.ok && text.startsWith("{")) { console.error(`from ${url}`); return JSON.parse(text); }
      console.error(`${url}: ${res.status}, busy`);
    } catch (e) { console.error(`${url}: ${e.message}`); }
  }
  throw new Error("every Overpass server is busy; try again later");
}

const saveTo = process.argv[2] === "--save" ? process.argv[3] : null;
const data = process.argv[2] && !saveTo ? JSON.parse(readFileSync(process.argv[2], "utf8")) : await fetchOverpass();
if (saveTo) writeFileSync(saveTo, JSON.stringify(data));
const asOf = data.osm3s.timestamp_osm_base.slice(0, 10);
const places = data.elements.map(e => toPlace(e, asOf)).filter(Boolean)
  .sort((a, b) => a.type.localeCompare(b.type) || a.name.localeCompare(b.name));

const count = {};
for (const p of places) count[p.type] = (count[p.type] ?? 0) + 1;
const fridges = data.elements.filter(e => e.tags?.amenity === "food_sharing" && toPlace(e, asOf)).length;
const students = data.elements.filter(e => e.tags && studentsOnly(e.tags)).map(e => `${e.type}/${e.id} ${e.tags.name ?? "(no name)"}`);
console.error(`OSM data as of ${asOf}: ${data.elements.length} elements, kept ${places.length}`, count,
  `(${fridges} of the food-bank ones are amenity=food_sharing);`,
  `skipped ${data.elements.length - places.length} (no name, not a food place, no position, or students only: ${students.length}${students.length ? ` = ${students.join("; ")}` : ""})`);

const q = v => v === null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const COLS = ["osm_type", "osm_id", "name", "type", "address", "hours", "phone", "website", "latitude", "longitude", "as_of"];
console.log(`-- Los Angeles County food places from OpenStreetMap (© OpenStreetMap contributors, ODbL 1.0), data as of ${asOf}:
-- ${places.length} places (${Object.entries(count).map(([t, n]) => `${n} ${t}`).join(", ")}). Replaces every row; the table is M9's.
-- Generated by scripts/fetch-osm-places.mjs; specs 2026-10-02-m9-real-map-design.md §3.2, 2026-10-07-m13-map-near-me-design.md §3.4.

delete from public.resources;

insert into public.resources (${COLS.join(", ")}) values
${places.map(p => `  (${COLS.map(c => q(p[c])).join(", ")})`).join(",\n")};`);
