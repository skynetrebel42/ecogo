// fetch-osm-places.mjs — snapshot of Los Angeles County food places from OpenStreetMap (M9).
//
//   node scripts/fetch-osm-places.mjs > m9.sql              asks Overpass (tries three servers)
//   node scripts/fetch-osm-places.mjs saved.json > m9.sql   reuses a saved Overpass response
//
// Prints a migration that replaces every `resources` row; counts go to stderr. Review the SQL, then apply it as a
// new migration (never edit an applied one). "as of" is the OSM data's own timestamp, not today's date: public
// Overpass mirrors can lag the live map by months.
// Spec: docs/superpowers/specs/2026-10-02-m9-real-map-design.md §3.

import { readFileSync } from "node:fs";
import { toPlace } from "../src/lib/osmPlaces.ts";

const QUERY = `[out:json][timeout:180];area["wikidata"="Q104994"]->.la;(
nwr["amenity"="food_bank"](area.la);nwr["social_facility"="food_bank"](area.la);
nwr["amenity"="marketplace"](area.la);nwr["leisure"="garden"]["garden:type"="community"](area.la););out tags center;`;
const SERVERS = ["https://overpass-api.de/api/interpreter", "https://overpass.private.coffee/api/interpreter",
  "https://overpass.kumi.systems/api/interpreter"];

async function fetchOverpass() {
  for (const url of SERVERS) {
    try {
      const res = await fetch(url, { method: "POST", body: new URLSearchParams({ data: QUERY }),
        headers: { "User-Agent": "EcoGo/0.1 (personal project)" }, signal: AbortSignal.timeout(200_000) });
      const text = await res.text();
      if (res.ok && text.startsWith("{")) { console.error(`from ${url}`); return JSON.parse(text); }
      console.error(`${url}: ${res.status}, busy`);
    } catch (e) { console.error(`${url}: ${e.message}`); }
  }
  throw new Error("every Overpass server is busy; try again later");
}

const data = process.argv[2] ? JSON.parse(readFileSync(process.argv[2], "utf8")) : await fetchOverpass();
const asOf = data.osm3s.timestamp_osm_base.slice(0, 10);
const places = data.elements.map(e => toPlace(e, asOf)).filter(Boolean)
  .sort((a, b) => a.type.localeCompare(b.type) || a.name.localeCompare(b.name));

const count = {};
for (const p of places) count[p.type] = (count[p.type] ?? 0) + 1;
console.error(`OSM data as of ${asOf}: ${data.elements.length} elements, kept ${places.length}`, count,
  `skipped ${data.elements.length - places.length} (no name, not a food place, or no position)`);

const q = v => v === null ? "null" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const COLS = ["osm_type", "osm_id", "name", "type", "address", "hours", "phone", "website", "latitude", "longitude", "as_of"];
console.log(`-- M9: real Los Angeles County food places from OpenStreetMap (© OpenStreetMap contributors, ODbL 1.0),
-- data as of ${asOf}. Generated by scripts/fetch-osm-places.mjs; spec 2026-10-02-m9-real-map-design.md §3.2.

delete from public.resources;

alter table public.resources
  drop column rating,
  drop column description,
  add column osm_type text not null check (osm_type in ('node', 'way', 'relation')),
  add column osm_id   bigint not null,
  add column website  text,
  add column as_of    date not null,
  add constraint resources_osm_unique unique (osm_type, osm_id),
  drop constraint resources_type_check,
  add constraint resources_type_check check (type in ('food-bank', 'farmers-market', 'community-garden'));

insert into public.resources (${COLS.join(", ")}) values
${places.map(p => `  (${COLS.map(c => q(p[c])).join(", ")})`).join(",\n")};`);
