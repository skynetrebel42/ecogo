// build-usda-words.mjs — 066 R4: the words of USDA FoodData Central's ingredient lists, for the label reader's name
// suggestions. Reads the live `foods` table (EcoGo's copy of USDA Branded Foods; "USDA FoodData Central data are in
// the public domain", CC0 1.0) once with the public key, paged along the primary key, and writes
// src/lib/data/usda-words.ts: every word of 5+ letters (accents folded, upper case) found in at least `min` products.
// Run once per USDA import; the app and the build never query for it.
//   node --env-file=<path to .env> scripts/build-usda-words.mjs [min=20]
import { writeFileSync } from "node:fs";
import { createClient } from "@supabase/supabase-js";

const min = Number(process.argv[2] ?? 20);
const db = createClient(process.env.VITE_SUPABASE_URL, process.env.VITE_SUPABASE_PUBLISHABLE_KEY);
const counts = new Map();
let rows = 0, snapshot = "";
for (let last = ""; ;) {
  const { data, error } = await db.from("foods").select("barcode_key, ingredients, snapshot").gt("barcode_key", last).order("barcode_key").limit(1000);
  if (error) throw new Error(error.message || `reading foods failed (${error.code ?? "no code"})`);
  for (const r of data) {
    const words = new Set(r.ingredients.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase().match(/\p{L}{5,}/gu) ?? []);
    for (const w of words) counts.set(w, (counts.get(w) ?? 0) + 1);
    if (r.snapshot > snapshot) snapshot = r.snapshot;
  }
  rows += data.length;
  if (rows % 50000 < 1000) console.log(`${rows} products, ${counts.size} words`);
  if (data.length < 1000) break;
  last = data.at(-1).barcode_key;
}
for (const n of [5, 10, 20, 50, 100]) console.log(`in ≥ ${n} products: ${[...counts.values()].filter(c => c >= n).length} words`);
const words = [...counts].filter(([, c]) => c >= min).map(([w]) => w).sort();
// A .ts module, not .json: Node's test runner can't import JSON without an attribute that breaks Vite's dev server.
writeFileSync("src/lib/data/usda-words.ts", [
  `// Words of 5+ letters in at least ${min} of ${rows} USDA FoodData Central Branded Foods ingredient lists (release ${snapshot}), from scripts/build-usda-words.mjs. Source: U.S. Department of Agriculture, Agricultural Research Service. FoodData Central. fdc.nal.usda.gov (CC0 1.0).`,
  "// Generated by scripts/build-usda-words.mjs: re-run it, never hand-edit.",
  `export default ${JSON.stringify(words.join(" "))};`, "",
].join("\n"));
console.log(`wrote ${words.length} words from ${rows} products`);
